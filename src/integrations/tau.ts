/**
 * Tau integration module — first-class provider catalog sync for Tau.
 *
 * Zero-dependency: emits YAML using clean string templates, exactly like
 * `buildProvidersTauYaml` in codegen.ts. No external YAML libraries.
 *
 * - buildTauModelsYaml(catalog) — canonical YAML for ~/.tau/models.yml.
 * - buildTauInstalledSlice(catalog, env) — env-filtered slice.
 * - syncTauConfig(options) — write installed slice to Tau config paths.
 * - createTauModelRegistryLoader() — returns a function that loads the
 *   YAML as a string for downstream consumers.
 */
import type { CodegenInput } from "../codegen.ts";
import { buildInstalledTauYaml, keyEnvsOf } from "../codegen.ts";
import type { ProviderDef } from "../types.ts";

/** Re-export codegen's YAML generator for compatibility. */
export function buildTauModelsYaml(catalog: CodegenInput): string {
  const lines: string[] = [
    "# Code generated by @toxicwind/pinax for Tau — DO NOT EDIT BY HAND.",
    "# Regenerate with: bun run build  (in mesh/catalog)",
    "# Source of truth: mesh/catalog/src/data.ts",
    "# Generated at: " + new Date().toISOString(),
    "# Provenance: " + (catalog.provenance ?? "unknown"),
    "",
    "discovery:",
    "  type: openai-models-list",
    "  ollama: true",
    "  lm-studio: true",
    "  llama.cpp: true",
    "",
    "providers:",
    "  flock:",
    "    baseUrl: http://127.0.0.1:25193/v1",
    "    api: openai-completions",
    '    apiKey: "!cat /home/toxic/.tau/flock.key"',
    "    discovery:",
    "      type: openai-models-list",
  ];

  for (const d of catalog.defs) {
    if (d.enabled === false || d.routerLocal || d.name === "herd") {
      continue;
    }
    lines.push("  " + d.name + ":");
    lines.push("    baseUrl: " + d.baseUrl);
    lines.push("    api: openai-completions");
    if (d.maxConcurrency !== undefined) {
      lines.push("    maxConcurrency: " + d.maxConcurrency);
    }
    if (d.auth === "none") {
      lines.push("    auth: none");
    } else if (d.keyEnv) {
      lines.push("    apiKey: " + d.keyEnv);
    }
    if (d.adapter !== "none" && d.adapter !== "static") {
      lines.push("    discovery:");
      lines.push("      type: openai-models-list");
    } else if (d.staticModels && d.staticModels.length > 0) {
      lines.push("    models:");
      for (const id of d.staticModels) {
        const ctx = d.contextLengths?.[id];
        lines.push("      - id: " + id);
        if (ctx) lines.push("        contextWindow: " + ctx);
      }
    }
  }

  return lines.join("\n") + "\n";
}

/**
 * Installed slice for live Tau consumption.
 * Filters: skip disabled / routerLocal / herd; keep flock, hodos and
 * unauthenticated endpoints; otherwise only include providers whose
 * keyEnv (or keyEnvAlt pool) is present in env.
 */
export function buildTauInstalledSlice(
  catalog: CodegenInput,
  env: Record<string, string | undefined> = {},
): string {
  const present = (name?: string) => {
    if (!name) return false;
    const v = env[name];
    return typeof v === "string" && v.trim().length > 0;
  };

  const defs = catalog.defs.filter((d: ProviderDef) => {
    if (d.enabled === false || d.routerLocal) return false;
    if (d.name === "flock" || d.name === "hodos" || d.auth === "none")
      return true;
    const pool = keyEnvsOf(d);
    if (pool.length === 0) return true;
    return pool.some(present);
  });

  // Delegate to codegen's buildProvidersTauYaml for consistency.
  return buildInstalledTauYaml({ ...catalog, defs }, env);
}

/** Default Tau config paths. */
const DEFAULT_TAU_DESTS = [
  "/home/toxic/.tau/models.yml",
  "/home/toxic/estate/config/tau/models.yml",
];

/**
 * Write the installed slice to Tau config paths.
 * Best-effort — the build must not fail if directories don't exist.
 * Returns the array of written paths.
 */
export async function syncTauConfig(options?: {
  dests?: string[];
  env?: Record<string, string | undefined>;
}): Promise<string[]> {
  const dests = options?.dests ?? DEFAULT_TAU_DESTS;
  const env = options?.env ?? {};

  // Load environment from Tau and secrets files if available.
  let resolvedEnv: Record<string, string | undefined> = { ...env };
  try {
    const tauEnv = await Bun.file("/home/toxic/.tau/.env").text();
    for (const line of tauEnv.split("\n")) {
      const s = line.trim();
      if (!s || s.startsWith("#") || !s.includes("=")) continue;
      const eq = s.indexOf("=");
      const k = s.slice(0, eq).trim().replace(/^export\s+/, "");
      const v = s.slice(eq + 1).trim();
      if (k && !resolvedEnv[k]) resolvedEnv[k] = v;
    }
  } catch {
    // best-effort
  }
  try {
    const secrets = await Bun.file("/home/toxic/.secrets").text();
    for (const line of secrets.split("\n")) {
      const s = line.trim();
      if (!s || s.startsWith("#") || !s.includes("=")) continue;
      const eq = s.indexOf("=");
      const k = s.slice(0, eq).trim().replace(/^export\s+/, "");
      const v = s.slice(eq + 1).trim();
      if (k) resolvedEnv[k] = v;
    }
  } catch {
    // best-effort
  }

  // Need the real catalog data.
  const { PROVIDER_DEFS, MODEL_ALIASES, DEAD_MODEL_IDS } = await import(
    "../data.ts"
  );
  const catalog: CodegenInput = {
    defs: PROVIDER_DEFS,
    aliases: MODEL_ALIASES,
    deadIds: DEAD_MODEL_IDS,
    provenance: "@toxicwind/pinax src/data.ts",
  };

  const content = buildTauInstalledSlice(catalog, resolvedEnv);
  const written: string[] = [];

  for (const p of dests) {
    try {
      await Bun.write(p, content);
      written.push(p);
    } catch (e) {
      console.warn("skip Tau sync to " + p + ": " + (e as Error).message);
    }
  }

  return written;
}

/**
 * Create a Tau model registry loader.
 * Returns a function that loads the Tau models.yml as a raw YAML string
 * for downstream consumers to parse.
 */
export function createTauModelRegistryLoader(): (
  path?: string,
) => Promise<string> {
  return async (path = "/home/toxic/.tau/models.yml") => {
    try {
      return await Bun.file(path).text();
    } catch {
      return "";
    }
  };
}
