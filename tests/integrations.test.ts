/**
 * Integration tests: Tau and Kappa first-class modules.
 *
 * Tests Tau YAML generation, installed slice filtering, and Kappa JSON
 * generation (provider config, installed slice, dev cache format).
 * Verifies maxConcurrency serialization for freeinference (2).
 */
import { describe, expect, test } from "bun:test";
import {
  buildProvidersTauYaml,
  buildProvidersKappaJson,
  buildProvidersGo,
  buildProvidersRust,
  buildProvidersJson,
} from "../src/codegen.ts";
import type { CodegenInput } from "../src/codegen.ts";
import type { ProviderDef } from "../src/types.ts";

// Tau integration
import {
  buildTauModelsYaml,
  buildTauInstalledSlice,
  createTauModelRegistryLoader,
} from "../src/integrations/tau.ts";
import {
  buildKappaProviderConfig,
  buildKappaInstalledJson,
  buildKappaModelsDevJson,
} from "../src/integrations/kappa.ts";

function sampleDef(over: Partial<ProviderDef> = {}): ProviderDef {
  return {
    name: "groq",
    displayName: "Groq",
    baseUrl: "https://api.groq.com/openai/v1",
    keyEnv: "GROQ_API_KEY",
    auth: "bearer",
    adapter: "openai",
    seeds: ["groq-model-1"],
    ...over,
  };
}

function sampleInput(): CodegenInput {
  return {
    defs: [
      sampleDef(),
      sampleDef({
        name: "freeinference",
        displayName: "FreeInference",
        baseUrl: "https://freeinference.org/v1",
        keyEnv: "FREEINFERENCE_API_KEY",
        adapter: "openai",
        seeds: ["qwen3.6-35b"],
        maxConcurrency: 2,
        contextLengths: { "qwen3.6-35b": 262000 },
      }),
      sampleDef({
        name: "flock",
        baseUrl: "http://127.0.0.1:25193/v1",
        keyEnv: "",
        auth: "bearer",
        adapter: "openai",
        seeds: [],
      }),
    ],
    aliases: {},
    deadIds: [],
    provenance: "test",
  };
}

// ─── Tau YAML ────────────────────────────────────────────────────────
describe("tau: buildTauModelsYaml", () => {
  test("emits YAML with discovery, api, baseUrl, apiKey, maxConcurrency", () => {
    const yml = buildTauModelsYaml(sampleInput());
    expect(yml).toContain("# Code generated by @toxicwind/pinax for Tau");
    expect(yml).toContain("discovery:");
    expect(yml).toContain("  type: openai-models-list");
    expect(yml).toContain("flock:");
    expect(yml).toContain("groq:");
    expect(yml).toContain("baseUrl: https://api.groq.com/openai/v1");
    expect(yml).toContain("api: openai-completions");
    expect(yml).toContain("apiKey: GROQ_API_KEY");
    // maxConcurrency for freeinference
    expect(yml).toContain("freeinference:");
    expect(yml).toContain("maxConcurrency: 2");
  });

  test("freeinference gets maxConcurrency: 2 in Tau YAML", () => {
    const yml = buildTauModelsYaml(sampleInput());
    const lines = yml.split("\n");
    let inFreeinference = false;
    for (const line of lines) {
      if (line.trim() === "freeinference:") inFreeinference = true;
      if (inFreeinference && line.includes("maxConcurrency: 2")) {
        expect(true).toBe(true);
        return;
      }
    }
    throw new Error("freeinference maxConcurrency: 2 not found in Tau YAML");
  });
});

// ─── Tau installed slice ──────────────────────────────────────────────
describe("tau: buildTauInstalledSlice", () => {
  test("drops providers whose key is unset", () => {
    const slice = buildTauInstalledSlice(sampleInput(), {});
    expect(slice).toContain("flock:");
    expect(slice).not.toContain("groq:");
    expect(slice).not.toContain("freeinference:");
  });

  test("keeps providers whose key is present", () => {
    const slice = buildTauInstalledSlice(sampleInput(), {
      GROQ_API_KEY: "test-key",
    });
    expect(slice).toContain("flock:");
    expect(slice).toContain("groq:");
  });

  test("includes freeinference when its key is present", () => {
    const slice = buildTauInstalledSlice(sampleInput(), {
      FREEINFERENCE_API_KEY: "test-key",
    });
    expect(slice).toContain("freeinference:");
    expect(slice).toContain("maxConcurrency: 2");
  });
});

// ─── Tau model registry loader ───────────────────────────────────────
describe("tau: createTauModelRegistryLoader", () => {
  test("returns a function that parses YAML", () => {
    const loader = createTauModelRegistryLoader();
    expect(typeof loader).toBe("function");
  });

  test("returns empty object for nonexistent file", async () => {
    const loader = createTauModelRegistryLoader();
    const result = await loader("/nonexistent/path.yml");
    expect(result).toBe("");
  });
});

// ─── Kappa provider config ───────────────────────────────────────────
describe("kappa: buildKappaProviderConfig", () => {
  test("emits provider map with npm, options, models", () => {
    const config = buildKappaProviderConfig(sampleInput());
    expect(config).toBeDefined();
    expect(typeof config).toBe("object");
    // groq should be present
    const groq = (config as Record<string, unknown>)["groq"] as
      | Record<string, unknown>
      | undefined;
    expect(groq).toBeDefined();
    expect((groq?.npm as string | undefined)).toBe("@ai-sdk/openai-compatible");
    expect((groq?.options as Record<string, unknown>)?.baseURL).toBe(
      "https://api.groq.com/openai/v1",
    );
    expect((groq?.options as Record<string, unknown>)?.apiKey).toBe(
      "{env:GROQ_API_KEY}",
    );
  });

  test("freeinference has maxConcurrency: 2 in provider options", () => {
    const config = buildKappaProviderConfig(sampleInput());
    const fi = (config as Record<string, unknown>)["freeinference"] as
      | Record<string, unknown>
      | undefined;
    expect(fi).toBeDefined();
    const options = fi?.options as Record<string, unknown> | undefined;
    expect((options as any)?.maxConcurrency).toBe(2);
  });
});

// ─── Kappa installed JSON ────────────────────────────────────────────
describe("kappa: buildKappaInstalledJson", () => {
  test("emits full structure with $schema and provider map", () => {
    const json = buildKappaInstalledJson(
      sampleInput(),
      { GROQ_API_KEY: "test" },
    );
    const doc = JSON.parse(json);
    expect(doc.$schema).toBe("https://app.kappa.ai/config.json");
    expect(doc.contract).toBe("estate-pinax/kappa-catalog/v1");
    expect(doc.provider).toBeDefined();
    expect(doc.provider.groq).toBeDefined();
  });

  test("installed slice drops providers without keys", () => {
    const json = buildKappaInstalledJson(sampleInput(), {});
    const doc = JSON.parse(json);
    expect(doc.provider?.groq).toBeUndefined();
  });

  test("freeinference has maxConcurrency: 2 in installed JSON", () => {
    const json = buildKappaInstalledJson(
      sampleInput(),
      { FREEINFERENCE_API_KEY: "test" },
    );
    const doc = JSON.parse(json);
    const fi = doc.provider?.freeinference as Record<string, unknown> | undefined;
    expect((fi?.options as Record<string, unknown> | undefined)?.maxConcurrency).toBe(2);
  });
});

// ─── Kappa ModelsDev JSON ────────────────────────────────────────────
describe("kappa: buildKappaModelsDevJson", () => {
  test("emits Record<string, Provider> with id, name, env, models", () => {
    const devJson = buildKappaModelsDevJson(sampleInput());
    const groq = devJson["groq"] as Record<string, unknown> | undefined;
    expect(groq).toBeDefined();
    expect(groq?.id).toBe("groq");
    expect(groq?.name).toBe("Groq");
    expect(groq?.env).toBe("GROQ_API_KEY");
    expect(groq?.models).toEqual(["groq-model-1"]);
  });

  test("freeinference has maxConcurrency: 2 in dev JSON", () => {
    const devJson = buildKappaModelsDevJson(sampleInput());
    const fi = devJson["freeinference"] as { id?: string; maxConcurrency?: number } | undefined;
    expect(fi?.id).toBe("freeinference");
    expect(fi?.maxConcurrency).toBe(2);
  });
});

// ─── maxConcurrency serialization ────────────────────────────────────
describe("maxConcurrency serialization", () => {
  test("freeinference gets maxConcurrency: 2 in providers.json", () => {
    const doc = JSON.parse(buildProvidersJson(sampleInput()));
    const fi = doc.providers.find(
      (p: Record<string, unknown>) => p.name === "freeinference",
    );
    expect(fi?.maxConcurrency).toBe(2);
  });

  test("providers without maxConcurrency omit the field", () => {
    const doc = JSON.parse(buildProvidersJson(sampleInput()));
    const groq = doc.providers.find(
      (p: Record<string, unknown>) => p.name === "groq",
    );
    expect(groq?.maxConcurrency).toBeUndefined();
  });

  test("freeinference gets maxConcurrency: 2 in Tau YAML", () => {
    const yml = buildProvidersTauYaml(sampleInput());
    expect(yml).toContain("maxConcurrency: 2");
  });

  test("freeinference gets maxConcurrency: 2 in Kappa provider options", () => {
    const config = buildKappaProviderConfig(sampleInput());
    const fi = config["freeinference"] as Record<string, unknown>;
    expect((fi.options as Record<string, unknown>).maxConcurrency).toBe(2);
  });

  test("freeinference gets MaxConcurrency: 2 in Go output", () => {
    const go = buildProvidersGo(sampleInput());
    // The freeinference entry should have MaxConcurrency: 2
    expect(go).toContain("MaxConcurrency: 2");
  });

  test("freeinference gets max_concurrency: 2 in Rust output", () => {
    const rs = buildProvidersRust(sampleInput());
    expect(rs).toContain("max_concurrency: 2");
  });
});
